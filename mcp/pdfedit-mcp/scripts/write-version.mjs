// Writes src/version.ts from package.json so the server reports its real
// version without reading a file at runtime (a Cloudflare Worker bundle has
// no filesystem; createRequire('../package.json') fails there).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const out = `// Generated by scripts/write-version.mjs from package.json; do not edit.\nexport const SERVER_VERSION = '${version}';\n`;
const target = join(root, 'src', 'version.ts');
let current = '';
try { current = readFileSync(target, 'utf8'); } catch {}
if (current !== out) writeFileSync(target, out);
